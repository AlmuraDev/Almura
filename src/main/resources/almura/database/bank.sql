-- Banking's tables, as 3.5's (db/bank/database.sql), written for both H2 2 and PostgreSQL. The balances themselves are in the economy
-- plugin: each account is the economy's virtual account named economy_id.

create table if not exists bank_account
(
  rec_no       int          generated by default as identity primary key,
  created      timestamp    default current_timestamp not null,
  owner        uuid         not null,
  name         varchar(64)  not null,
  economy_id   varchar(64)  not null
);

create table if not exists bank_account_member
(
  rec_no       int          generated by default as identity primary key,
  account      int          not null references bank_account (rec_no) on update cascade on delete cascade,
  member       uuid         not null,
  can_withdraw boolean      default false not null
);

-- History stays after an account is closed, so it has no reference to it
create table if not exists bank_transaction
(
  rec_no       int          generated by default as identity primary key,
  created      timestamp    default current_timestamp not null,
  account      int          not null,
  account_name varchar(64)  not null,
  owner        uuid         not null,
  actor        uuid         not null,
  type         varchar(32)  not null,
  amount       numeric(13, 2) default 0 not null
);

create index if not exists bank_transaction_account on bank_transaction (account);
create index if not exists bank_transaction_actor on bank_transaction (actor);
create index if not exists bank_transaction_owner on bank_transaction (owner);
