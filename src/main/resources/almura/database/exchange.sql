-- The exchanges' tables, as 3.5's (db/axs/database.sql), written for both H2 2 and PostgreSQL. A listed item is kept as one item (its
-- components included) encoded as JSON with the game's item codec, and how many of it there are.

create table if not exists axs
(
  id           varchar(255) primary key,
  created      timestamp    default current_timestamp not null,
  creator      uuid         not null,
  name         varchar(255) not null,
  permission   varchar(255) not null,
  is_hidden    boolean      default false not null
);

create table if not exists axs_list_item
(
  rec_no           int            generated by default as identity primary key,
  created          timestamp      default current_timestamp not null,
  axs              varchar(255)   not null references axs (id) on update cascade on delete cascade,
  seller           uuid           not null,
  item             varchar(1000000) not null,
  quantity         int            default 1 not null,
  list_index       int            default 0 not null,
  last_known_price numeric(15, 2) null,
  is_hidden        boolean        default false not null
);

create table if not exists axs_for_sale_item
(
  rec_no       int            generated by default as identity primary key,
  created      timestamp      default current_timestamp not null,
  list_item    int            not null references axs_list_item (rec_no) on update cascade on delete cascade,
  price        numeric(15, 2) default 0 not null,
  is_hidden    boolean        default false not null
);

create table if not exists axs_transaction
(
  rec_no        int            generated by default as identity primary key,
  created       timestamp      default current_timestamp not null,
  for_sale_item int            not null references axs_for_sale_item (rec_no) on update cascade on delete cascade,
  buyer         uuid           not null,
  price         numeric(15, 2) default 0 not null,
  quantity      int            default 1 not null
);

create index if not exists axs_list_item_axs on axs_list_item (axs);
create index if not exists axs_list_item_seller on axs_list_item (seller);
create index if not exists axs_for_sale_item_list_item on axs_for_sale_item (list_item);
create index if not exists axs_transaction_for_sale_item on axs_transaction (for_sale_item);
