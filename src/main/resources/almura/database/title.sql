-- Titles' tables, as 3.5's (db/title/database.sql), written for both H2 2 and PostgreSQL. The titles a player may pick come from each title's
-- permission; the one they picked is in title_select, and what they had before in title_select_history.

create table if not exists title
(
  id           varchar(255) primary key,
  created      timestamp    default current_timestamp not null,
  creator      uuid         not null,
  permission   varchar(255) not null,
  content      varchar(255) not null,
  is_hidden    boolean      default false not null
);

create table if not exists title_select
(
  holder       uuid         primary key,
  created      timestamp    default current_timestamp not null,
  title        varchar(255) not null references title (id) on update cascade on delete cascade
);

create table if not exists title_select_history
(
  rec_no       int          generated by default as identity primary key,
  created      timestamp    default current_timestamp not null,
  holder       uuid         not null,
  old_title    varchar(255) not null
);

create index if not exists title_select_history_holder on title_select_history (holder);
