-- Stores' tables, from 3.5's (db/store/database.sql), written for both H2 2 and PostgreSQL. 3.5 kept buying and selling items in two pairs
-- of tables (the item, and its NBT apart); here both sides share one table with a side column, and the item is its codec's JSON, with its
-- components (count 1: a listing's quantity is its own column).

create table if not exists store
(
  id           varchar(255) primary key,
  created      timestamp    default current_timestamp not null,
  creator      uuid         not null,
  name         varchar(255) not null,
  permission   varchar(255) not null,
  is_hidden    boolean      default false not null
);

-- side: BUY (players buy it from the store) or SELL (players sell it to the store). quantity -1 has no end. A listing taken down is hidden,
-- so its transactions keep pointing at it
create table if not exists store_item
(
  rec_no       int          generated by default as identity primary key,
  created      timestamp    default current_timestamp not null,
  store        varchar(255) not null references store (id) on update cascade on delete cascade,
  side         varchar(8)   not null,
  item         text         not null,
  quantity     int          default -1 not null,
  price        numeric(13, 2) default 0 not null,
  sort_index   int          default 0 not null,
  is_hidden    boolean      default false not null
);

create table if not exists store_transaction
(
  rec_no       int          generated by default as identity primary key,
  created      timestamp    default current_timestamp not null,
  store_item   int          not null references store_item (rec_no) on update cascade on delete cascade,
  side         varchar(8)   not null,
  player       uuid         not null,
  quantity     int          default 1 not null,
  price        numeric(13, 2) default 0 not null
);

create index if not exists store_item_store on store_item (store);
create index if not exists store_transaction_item on store_transaction (store_item);
